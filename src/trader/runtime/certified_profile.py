"""Propose a paper-certified capability profile from a certification report
(``trader paper certify-profile``; architecture.md §4 evidence levels).

The proposal starts from the base profile the run used (configs/capabilities/
alpaca_documented.yaml) and changes only what the report *demonstrates* in paper:

* ``fractional.limit.day``: the run's fractional LIMIT DAY buy was accepted and resting while the
  broker clock said the market was open -> ``supported: true``, ``PAPER_DEMONSTRATED``;
* ``fractional.market.day``: the fractional MARKET DAY buy and the sell both filled, every fill is
  in the ledger and the account is flat again -> ``PAPER_DEMONSTRATED``;
* ``client_order_id_unique``: Alpaca refused the repeated client order ID and exactly one order
  with that ID exists, unfilled -> ``PAPER_DEMONSTRATED``;
* ``order_visibility_lookups`` / ``order_visibility_window_seconds``: only when every submitted
  order (at least :data:`VISIBILITY_MIN_SAMPLES`) became visible by client ID, with a wide margin:
  lookups = max(3, observed + 2), window = max(30 s, 10 x observed seconds) - never less
  conservative than the base;
* ``rate_limit_per_minute``: the ``X-RateLimit-Limit`` header Alpaca returned (never higher than a
  limit the base already states).

Only a demonstrated *duplicate acceptance* changes a capability to ``supported: false``. Any other
refusal (Alpaca refusing the fractional limit buy, say) is listed as a note for the owner and
changes nothing: the cause cannot be attributed safely. Anything not demonstrated keeps the base
value (UNKNOWN stays UNKNOWN), the environment stays ``paper`` and paper evidence never certifies
live availability. The owner reviews the proposal before pointing configs/paper.yaml at it.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from decimal import Decimal
from typing import Any, Final

import yaml

from trader.domain.capabilities import (
    CLIENT_ORDER_ID_UNIQUE,
    FRACTIONAL_LIMIT_DAY,
    FRACTIONAL_MARKET_DAY,
    BrokerCapabilities,
    Capability,
)
from trader.domain.orders import BrokerOrderStatus, OrderState
from trader.domain.types import EvidenceLevel, iso_utc
from trader.runtime.certification import CertificationRefused, CertificationReport

VISIBILITY_MIN_SAMPLES: Final = 3
VISIBILITY_MIN_LOOKUPS: Final = 3
VISIBILITY_LOOKUP_MARGIN: Final = 2
VISIBILITY_MIN_WINDOW_SECONDS: Final = 30
VISIBILITY_WINDOW_FACTOR: Final = 10
PROFILE_BROKER: Final = "alpaca"
_RESTING = frozenset({BrokerOrderStatus.ACCEPTED.value, BrokerOrderStatus.PARTIALLY_FILLED.value})


@dataclass(frozen=True, slots=True)
class ProfileProposal:
    profile: BrokerCapabilities
    changes: tuple[str, ...]
    kept: tuple[str, ...]
    notes: tuple[str, ...] = ()

    def yaml_text(self, *, report_ref: str, base_ref: str, report_hash: str) -> str:
        header = [
            "# PROPOSED Alpaca paper capability profile - generated by "
            "`trader paper certify-profile`.",
            f"# Source report: {report_ref} (report hash {report_hash}).",
            f"# Base profile:  {base_ref}.",
            "# Only what the report demonstrates in PAPER was changed; paper evidence never "
            "certifies live.",
            "# Review it, then point configs/paper.yaml at it and run `trader docs build`.",
            "# Changes:",
            *[f"#   - {line}" for line in self.changes],
            "# Unchanged (not demonstrated by this report):",
            *[f"#   - {line}" for line in self.kept],
        ]
        if self.notes:
            header += ["# Notes for the reviewer:", *[f"#   - {line}" for line in self.notes]]
        data = _strip_schema_version(self.profile.model_dump(mode="json"))
        body = yaml.safe_dump(data, sort_keys=False, allow_unicode=False, width=100)
        return "\n".join(header) + "\n" + body


def _strip_schema_version(value: Any) -> Any:
    if isinstance(value, dict):
        return {k: _strip_schema_version(v) for k, v in value.items() if k != "schema_version"}
    if isinstance(value, list):
        return [_strip_schema_version(v) for v in value]
    return value


def _cell(cap: Capability) -> str:
    if cap.supported is None:
        return "UNKNOWN"
    return f"{'yes' if cap.supported else 'no'} ({cap.evidence.value.lower()})"


@dataclass
class _Evidence:
    base: BrokerCapabilities
    source: str
    capabilities: dict[str, Capability] = field(default_factory=dict)
    changes: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def demonstrate(self, name: str, supported: bool, notes: str) -> None:
        before = self.base.capability(name)
        self.capabilities[name] = Capability(
            supported=supported,
            evidence=EvidenceLevel.PAPER_DEMONSTRATED,
            source=self.source,
            notes=notes,
        )
        self.changes.append(f"{name}: {_cell(before)} -> {_cell(self.capabilities[name])}")


def propose_certified_profile(
    report: CertificationReport, base: BrokerCapabilities, *, report_ref: str
) -> ProfileProposal:
    """The proposed profile (see the module docstring); refuses an unusable report."""
    report = report.verified()
    if base.broker != PROFILE_BROKER or base.environment != "paper":
        raise CertificationRefused(
            f"the base profile {base.profile_version} is not an Alpaca paper profile"
        )
    if report.capability_profile_version != base.profile_version:
        raise CertificationRefused(
            f"the report was made with {report.capability_profile_version}, not "
            f"{base.profile_version}: pass the base profile the run used"
        )
    if report.status == "REFUSED" or report.broker_submissions == 0:
        raise CertificationRefused("the report sent no orders: nothing is demonstrated")
    evidence = _Evidence(base=base, source=f"paper certification {report.run_id} ({report_ref})")
    _limit_day(report, evidence)
    _market_day(report, evidence)
    _client_id(report, evidence)
    updates: dict[str, Any] = {
        "capabilities": {**base.capabilities, **evidence.capabilities},
        "profile_version": f"alpaca-paper-certified-{report.finished_at:%Y-%m-%d}",
        "as_of": report.finished_at,
    }
    visibility = _visibility(report, base)
    if visibility is not None:
        lookups, window = visibility
        updates["order_visibility_lookups"] = lookups
        updates["order_visibility_window_seconds"] = window
        evidence.changes.append(
            f"order visibility: {base.order_visibility_lookups} lookups / "
            f"{base.order_visibility_window_seconds} s -> {lookups} lookups / {window} s"
        )
    else:
        evidence.notes.append(
            "order visibility not certified: needs at least "
            f"{VISIBILITY_MIN_SAMPLES} orders, every one visible by client order ID"
        )
    limit = _rate_limit(report, base)
    if limit is not None:
        updates["rate_limit_per_minute"] = limit
        evidence.changes.append(f"rate_limit_per_minute: {base.rate_limit_per_minute} -> {limit}")
    for record in report.reconciliations:
        if record.status != "PASSED":
            evidence.notes.append(
                f"reconciliation {record.label} {record.status}: {'; '.join(record.problems)}"
            )
    if not evidence.changes:
        raise CertificationRefused("the report demonstrates nothing; no profile proposed")
    profile = BrokerCapabilities.model_validate(
        {**base.model_dump(mode="python"), **updates}, strict=False
    )
    kept = tuple(
        f"{name}: {_cell(cap)}"
        for name, cap in sorted(base.capabilities.items())
        if name not in evidence.capabilities
    )
    return ProfileProposal(
        profile=profile,
        changes=tuple(evidence.changes),
        kept=kept,
        notes=tuple(evidence.notes),
    )


def _limit_day(report: CertificationReport, evidence: _Evidence) -> None:
    order = next(
        (o for o in report.orders if o.step == "fractional_limit_day" and o.side == "BUY"), None
    )
    if order is None:
        return
    if (
        report.passed("fractional_limit_day")
        and order.market_open
        and order.state_after_submit == OrderState.ACKNOWLEDGED.value
        and order.broker_status_after_submit in _RESTING
        and order.quantity != order.quantity.to_integral_value()
    ):
        evidence.demonstrate(
            FRACTIONAL_LIMIT_DAY,
            True,
            f"fractional LIMIT DAY buy {order.quantity} @ {order.limit_price} accepted in regular "
            f"hours ({order.broker_status_after_submit}); cancelled by the run",
        )
    elif order.refusal is not None:
        evidence.notes.append(
            f"{FRACTIONAL_LIMIT_DAY} not demonstrated: refused by {order.refused_by}: "
            f"{order.refusal}"
        )


def _market_day(report: CertificationReport, evidence: _Evidence) -> None:
    orders = [o for o in report.orders if o.step == "fractional_market_day"]
    buy = next((o for o in orders if o.side == "BUY"), None)
    sell = next((o for o in orders if o.side == "SELL"), None)
    if buy is None:
        return
    filled = all(
        o is not None
        and o.final_state == OrderState.FILLED.value
        and o.fills
        and sum((f.quantity for f in o.fills), start=Decimal(0)) == o.quantity
        for o in (buy, sell)
    )
    fractional = buy.quantity != buy.quantity.to_integral_value()
    if filled and fractional and report.flat_after_round_trip is True:
        evidence.demonstrate(
            FRACTIONAL_MARKET_DAY,
            True,
            f"fractional MARKET DAY buy {buy.quantity} and sell filled; account flat afterwards",
        )
    elif buy.refusal is not None:
        evidence.notes.append(
            f"{FRACTIONAL_MARKET_DAY} not demonstrated: refused by {buy.refused_by}: {buy.refusal}"
        )


def _client_id(report: CertificationReport, evidence: _Evidence) -> None:
    dup = report.duplicate
    if dup is None:
        return
    if (
        report.passed("client_order_id_unique")
        and dup.outcome == "REJECTED_DUPLICATE"
        and dup.broker_orders_with_client_id == 1
        and dup.filled_quantity == 0
    ):
        evidence.demonstrate(
            CLIENT_ORDER_ID_UNIQUE,
            True,
            "a repeated client order ID from a fresh adapter was refused; one order existed",
        )
    elif dup.outcome == "ACCEPTED_TWICE" or dup.broker_orders_with_client_id > 1:
        evidence.demonstrate(CLIENT_ORDER_ID_UNIQUE, False, f"duplicate accepted: {dup.detail}")
    else:
        evidence.notes.append(f"{CLIENT_ORDER_ID_UNIQUE} not demonstrated: {dup.outcome}")


def _visibility(report: CertificationReport, base: BrokerCapabilities) -> tuple[int, int] | None:
    samples = report.visibility
    if len(samples) < VISIBILITY_MIN_SAMPLES or not all(s.visible for s in samples):
        return None
    lookups = max(
        VISIBILITY_MIN_LOOKUPS, max(s.lookups for s in samples) + VISIBILITY_LOOKUP_MARGIN
    )
    seconds = max(s.seconds for s in samples)
    window = max(VISIBILITY_MIN_WINDOW_SECONDS, math.ceil(seconds * VISIBILITY_WINDOW_FACTOR))
    if base.order_visibility_lookups is not None:
        lookups = max(lookups, base.order_visibility_lookups)
    if base.order_visibility_window_seconds is not None:
        window = max(window, base.order_visibility_window_seconds)
    return lookups, window


def _rate_limit(report: CertificationReport, base: BrokerCapabilities) -> int | None:
    raw = report.rate_limit_headers.get("X-RateLimit-Limit")
    if raw is None or not raw.strip().isdigit():
        return None
    observed = int(raw.strip())
    if observed <= 0:
        return None
    if base.rate_limit_per_minute is not None:
        observed = min(observed, base.rate_limit_per_minute)
    return observed


def proposal_summary(proposal: ProfileProposal) -> list[str]:
    out = [
        f"proposed profile {proposal.profile.profile_version} ({iso_utc(proposal.profile.as_of)})"
    ]
    out += [f"  changed: {line}" for line in proposal.changes]
    out += [f"  kept   : {line}" for line in proposal.kept]
    out += [f"  note   : {line}" for line in proposal.notes]
    return out


