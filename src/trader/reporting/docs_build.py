"""Regenerate computed sections of the M0 documents between explicit markers.

``<!-- BEGIN GENERATED: name -->`` ... ``<!-- END GENERATED: name -->``. Hand-written text
outside the markers is never touched. ``--check`` fails if a committed document is stale.
"""

from __future__ import annotations

import re
from pathlib import Path

from trader.config.policy import load_policy
from trader.reporting.feasibility import generated_sections

TARGETS = {
    "docs/cost_feasibility.md": (
        "dollar-table",
        "fee-table",
        "max-size-table",
        "crypto-table",
        "cfd-table",
    ),
    "docs/broker_capabilities.md": ("capability-matrix",),
}


def _render(text: str, sections: dict[str, str], names: tuple[str, ...], path: str) -> str:
    for name in names:
        pattern = re.compile(
            rf"(<!-- BEGIN GENERATED: {re.escape(name)} -->\n)(.*?)(<!-- END GENERATED: {re.escape(name)} -->)",
            re.DOTALL,
        )
        if not pattern.search(text):
            raise ValueError(f"{path} lacks the generated section markers for {name!r}")
        body = (
            "<!-- generated by `trader docs build`; do not edit by hand -->\n"
            + sections[name]
            + "\n"
        )

        def _replace(match: re.Match[str], body: str = body) -> str:
            return match.group(1) + body + match.group(3)

        text = pattern.sub(_replace, text)
    return text


def build_docs(repo_root: Path, *, check: bool = False) -> list[str]:
    policy = load_policy(repo_root / "configs" / "policy" / "base.yaml")
    sections = generated_sections(repo_root, policy)
    stale: list[str] = []
    for rel, names in TARGETS.items():
        path = repo_root / rel
        current = path.read_text(encoding="utf-8")
        rendered = _render(current, sections, names, rel)
        if rendered != current:
            stale.append(rel)
            if not check:
                path.write_text(rendered, encoding="utf-8", newline="\n")
    return stale
